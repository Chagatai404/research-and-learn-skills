"""Archive only the retired Research OS user integrations on this computer."""

import argparse
import copy
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import re
import shutil
import subprocess
import tomllib


SKILLS = ("audit", "defend", "learn", "manimgx", "notes-to-latex", "prepare", "research")
SERVER = "research-os"
PLUGIN = "research-and-learn@research-and-learn-local"
HOOK_FRAGMENT = "from ros.cli import main; main(['brief', '--text'])"
CONFIGS = (".codex/config.toml", ".claude.json", ".claude/settings.json")


def read(path):
    data = path.read_text(encoding="utf-8")
    return tomllib.loads(data) if path.suffix == ".toml" else json.loads(data)


def skill_dirs(home):
    manifest = read(home / ".research-os-install.json")["files"]
    for base in (".agents/skills", ".claude/skills"):
        for name in SKILLS:
            relative = f"{base}/{name}"
            path = home / relative
            if path.resolve() != path or not path.is_dir():
                raise ValueError(f"Unexpected skill directory: {path}")
            recorded = {
                key: digest for key, digest in manifest.items() if key.startswith(relative + "/")
            }
            current = {}
            for file in path.rglob("*"):
                if file.resolve() != file:
                    raise ValueError(f"Unexpected link in skill directory: {file}")
                if file.is_file():
                    current[file.relative_to(home).as_posix()] = hashlib.sha256(file.read_bytes()).hexdigest()
            if not recorded or current != recorded:
                raise ValueError(f"Skill files differ from installer hashes: {path}")
            yield relative


def desired_configs(source):
    expected = {relative: read(source / relative) for relative in CONFIGS}
    codex, claude, settings = (expected[relative] for relative in CONFIGS)
    if codex["plugins"][PLUGIN]["enabled"] is not True or settings["enabledPlugins"][PLUGIN] is not True:
        raise ValueError("Research and Learn must already be enabled on both hosts")
    for key, app in (("mcp_servers", codex), ("mcpServers", claude)):
        table = app[key]
        if table[SERVER]["args"] != ["-m", "ros", "mcp"] or "scientific-research-os" not in table[SERVER]["env"]["PYTHONPATH"]:
            raise ValueError("Unexpected Research OS MCP entry")
        del table[SERVER]
        if not table:
            del app[key]
    groups = settings["hooks"]["SessionStart"]
    matching = [
        group for group in groups
        if list(group) == ["hooks"] and len(group["hooks"]) == 1
        and group["hooks"][0]["type"] == "command"
        and HOOK_FRAGMENT in group["hooks"][0]["command"]
    ]
    if len(matching) != 1:
        raise ValueError("Expected exactly one standalone ROS session hook")
    groups.remove(matching[0])
    return expected


def repair_codex(home, backup, expected):
    path = home / CONFIGS[0]
    original = (backup / CONFIGS[0]).read_bytes()
    pattern = rb"(?m)^# research-os:begin \(generated by ros install\)\r?\n\[mcp_servers\.research-os\]\r?\n[^\r\n]+\r?\n[^\r\n]+\r?\n[^\r\n]+\r?\n"
    cleaned, count = re.subn(pattern, b"", original)
    if count != 1 or tomllib.loads(cleaned.decode("utf-8")) != expected:
        raise ValueError("Unable to isolate the Codex Research OS MCP table")
    current = read(path)
    normalized = copy.deepcopy(expected)
    node_repl = normalized.get("mcp_servers", {}).get("node_repl", {})
    if node_repl.get("args") == []:
        del node_repl["args"]
    if current not in (expected, normalized):
        raise ValueError("Codex settings changed outside the expected CLI normalization")
    temporary = path.with_name("config.research-and-learn.tmp")
    with temporary.open("xb") as file:
        file.write(cleaned)
    temporary.replace(path)


def archive(home, backup, expected):
    repair_codex(home, backup, expected[CONFIGS[0]])
    for relative, desired in expected.items():
        if read(home / relative) != desired:
            raise ValueError(f"Unrelated configuration changed: {relative}")
    for relative in skill_dirs(home):
        target = backup / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        if target.resolve() != target or target.exists():
            raise ValueError(f"Unexpected destination: {target}")
        (home / relative).rename(target)
    print("Removed the two MCP registrations and one startup hook. Archived the legacy skills.")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--apply", action="store_true")
    parser.add_argument("--finish", type=Path)
    args = parser.parse_args()
    home = Path.home().resolve()
    skills = list(skill_dirs(home))
    if args.finish:
        backup = args.finish.resolve()
        if backup.parent != home / ".research-and-learn-backups" or not backup.name.startswith("legacy-hosts-"):
            raise ValueError("Unexpected backup location")
        archive(home, backup, desired_configs(backup))
        return
    expected = desired_configs(home)
    print(f"Verified {len(skills)} legacy skill directories and three host settings files")
    if not args.apply:
        return
    stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%S%fZ")
    backup = home / ".research-and-learn-backups" / f"legacy-hosts-{stamp}"
    if backup.resolve() != backup:
        raise ValueError("Backup destination must be on the same home volume")
    backup.mkdir(parents=True)
    print(f"Backup: {backup}", flush=True)
    originals = {}
    for relative in CONFIGS:
        path = home / relative
        target = backup / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(path, target)
        originals[relative] = read(path)
    (backup / "restore-map.json").write_text(json.dumps({"configs": CONFIGS, "skills": skills}, indent=2) + "\n", encoding="utf-8")

    binaries = [shutil.which(name + ".cmd") for name in ("codex", "claude")]
    if not all(binaries):
        raise RuntimeError("Codex and Claude CLI launchers are required")
    subprocess.run([binaries[0], "mcp", "remove", SERVER], check=True)
    subprocess.run([binaries[1], "mcp", "remove", "-s", "user", SERVER], check=True)
    settings_path = home / CONFIGS[2]
    if read(settings_path) != originals[CONFIGS[2]]:
        raise RuntimeError("Claude settings changed during cleanup")
    temporary = settings_path.with_name(f"settings.research-and-learn-{stamp}.tmp")
    temporary.write_text(json.dumps(expected[CONFIGS[2]], ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    temporary.replace(settings_path)
    archive(home, backup, expected)


if __name__ == "__main__":
    main()
